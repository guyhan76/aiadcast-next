// Include only Fontsource unicode-range files needed by the fixed bilingual lookbook titles.
// The editor continues to use its complete Noto Sans font for user-entered text.
import fs from 'node:fs';
const source='node_modules/@fontsource-variable/noto-serif-kr';
const campaigns=JSON.parse(fs.readFileSync('src/assets/lookbook-campaigns.json','utf8'));
const points=new Set([...campaigns.flatMap(c=>c.title.flat()).join('')].map(c=>c.codePointAt(0)));
const css=fs.readFileSync(`${source}/index.css`,'utf8');
const blocks=[...css.matchAll(/@font-face\s*\{[^}]*\}/g)].map(m=>m[0]).filter(block=>{
 const ranges=block.match(/unicode-range:\s*([^;]+)/)[1].split(',').map(x=>x.trim().replace(/^U\+/i,'').split('-').map(n=>parseInt(n,16)));
 return [...points].some(p=>ranges.some(([lo,hi=lo])=>p>=lo&&p<=hi));
});
const result=blocks.join('\n\n').replaceAll('url(./files/','url(../node_modules/@fontsource-variable/noto-serif-kr/files/');
fs.writeFileSync('src/lookbook-font.css','/* Generated by scripts/build-lookbook-font.mjs; original Fontsource files and license retained. */\n'+result+'\n');
fs.mkdirSync('public/licenses',{recursive:true});
fs.copyFileSync(`${source}/LICENSE`,'public/licenses/noto-serif-kr.txt');
console.log(`Lookbook font: ${blocks.length} unicode ranges for ${points.size} title characters`);
